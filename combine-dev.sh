#!/usr/bin/env bash
#
# Start (or re-attach to) a Combine AD development container.
#
#   ./combine-dev.sh                       # interactive shell, uses ./HiggsAnalysis/CombinedLimit
#   ./combine-dev.sh /other/CombinedLimit  # use a different checkout
#   ./combine-dev.sh -c 'combine-build'    # run one command and exit
#
# The source tree defaults to the CombinedLimit checkout sitting next to this
# script; override with an argument or with $COMBINE_SRC.
# Inside the shell, run `combine-build` to (re)build.
#
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

# Default to the Combine checkout next to this script, laid out the way CMS
# expects it: HiggsAnalysis/CombinedLimit.
SRC_ARG="${COMBINE_SRC:-$HERE/HiggsAnalysis/CombinedLimit}"
if [ $# -gt 0 ] && [ "$1" != "-c" ]; then
  SRC_ARG="$1"; shift
fi
if [ ! -d "$SRC_ARG" ]; then
  echo "error: no Combine checkout at $SRC_ARG" >&2
  echo "       clone one with:" >&2
  echo "         mkdir -p $HERE/HiggsAnalysis && \\" >&2
  echo "         git clone https://github.com/cms-analysis/HiggsAnalysis-CombinedLimit.git \\" >&2
  echo "             $HERE/HiggsAnalysis/CombinedLimit" >&2
  echo "       or pass a path / set COMBINE_SRC" >&2
  exit 1
fi
SRC="$(cd "$SRC_ARG" && pwd)"

NAME="${COMBINE_DEV_NAME:-combine-dev}"
GCC="${LCG_GCC:-gcc15}"
LCG_VIEW="${LCG_VIEW:-dev3/latest}"
ENV_FILE=/opt/combine-env.sh

case "$(uname -m)" in
  arm64|aarch64) DOCKER_PLATFORM=linux/arm64; LCG_ARCH="aarch64-el9-${GCC}-opt" ;;
  x86_64|amd64)  DOCKER_PLATFORM=linux/amd64; LCG_ARCH="x86_64-el9-${GCC}-opt"  ;;
  *) echo "unsupported host architecture: $(uname -m)" >&2; exit 1 ;;
esac
IMAGE="combine-cvmfs:${DOCKER_PLATFORM#linux/}"

if [ ! -f "$SRC/CMakeLists.txt" ]; then
  echo "error: $SRC does not look like a Combine checkout (no CMakeLists.txt)" >&2
  exit 1
fi

# Build the image on first use.
if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
  echo ">> building $IMAGE"
  docker build --platform "$DOCKER_PLATFORM" -t "$IMAGE" "$HERE"
fi

# Named volumes. The CVMFS cache is the important one: a cold cache turns a
# 1-second CMake configure into ~2 minutes of downloading, so never discard it.
for v in cvmfs-cache combine-build combine-install; do
  docker volume create "$v" >/dev/null
done

if ! docker ps --filter "name=^${NAME}$" --format '{{.Names}}' | grep -q .; then
  docker rm -f "$NAME" >/dev/null 2>&1 || true
  echo ">> starting container $NAME ($DOCKER_PLATFORM, $LCG_ARCH)"
  docker run -d --name "$NAME" --platform "$DOCKER_PLATFORM" \
    --cap-add SYS_ADMIN --device /dev/fuse \
    -v cvmfs-cache:/var/lib/cvmfs \
    -v combine-build:/build \
    -v combine-install:/install \
    -v "$SRC":/src -w /src \
    -v "$HERE/inputs":/inputs \
    "$IMAGE" sleep infinity >/dev/null
fi

# The entrypoint mounts CVMFS asynchronously with respect to us; wait for the
# view to appear before handing the user a shell that cannot source it.
SETUP="/cvmfs/sft.cern.ch/lcg/views/${LCG_VIEW}/${LCG_ARCH}/setup.sh"
for _ in $(seq 1 60); do
  if docker exec "$NAME" test -f "$SETUP" 2>/dev/null; then break; fi
  sleep 1
done
if ! docker exec "$NAME" test -f "$SETUP" 2>/dev/null; then
  VIEW_DIR="/cvmfs/sft.cern.ch/lcg/views/${LCG_VIEW}"
  if docker exec "$NAME" test -d "$VIEW_DIR" 2>/dev/null; then
    # CVMFS is fine; the requested platform is just not built in this view.
    echo "error: '$SETUP' does not exist." >&2
    echo "       platforms for ${LCG_ARCH%%-*} in view '$LCG_VIEW':" >&2
    docker exec "$NAME" ls "$VIEW_DIR" 2>/dev/null | grep "^${LCG_ARCH%%-*}-" | sed 's/^/         /' >&2
    echo "       pick one with LCG_GCC (e.g. LCG_GCC=gcc16) or change LCG_VIEW." >&2
  else
    echo "error: CVMFS did not come up, or view '$LCG_VIEW' does not exist." >&2
    echo "       check LCG_VIEW, and: docker exec $NAME cvmfs_config stat sft.cern.ch" >&2
  fi
  exit 1
fi

# Write the environment into the container so both interactive shells and
# `-c` one-shots use exactly the same setup.
docker exec -i "$NAME" tee "$ENV_FILE" >/dev/null <<EOF
# Generated by combine-dev.sh — do not edit inside the container.
# NOTE: LCG's setup.sh references unset variables, so never source it under 'set -u'.
source /cvmfs/sft.cern.ch/lcg/views/${LCG_VIEW}/${LCG_ARCH}/setup.sh
export PATH=/install/bin:\$PATH
export LD_LIBRARY_PATH=/install/lib:\$LD_LIBRARY_PATH
export PYTHONPATH=/install/python:\$PYTHONPATH
export ROOT_INCLUDE_PATH=/install/include:\$ROOT_INCLUDE_PATH
ulimit -s unlimited 2>/dev/null || true

combine-build() {
  ( cd /build \\
    && cmake -DCMAKE_INSTALL_PREFIX=/install \\
             -DCMAKE_BUILD_TYPE=RelWithDebInfo \\
             -DUSE_VDT=FALSE -DBUILD_TESTS="\${BUILD_TESTS:-FALSE}" /src \\
    && make install -j"\$(nproc)" )
}

if [ -n "\${PS1:-}" ]; then
  echo "LCG view : ${LCG_VIEW} / ${LCG_ARCH}"
  echo "ROOT     : \$(root-config --version)"
  echo "source   : /src   build: /build   install: /install"
  echo "commands : combine-build"
fi
EOF

# Run a single command if asked, otherwise open an interactive shell.
if [ $# -gt 0 ] && [ "$1" = "-c" ]; then
  shift
  exec docker exec -i "$NAME" bash -c "source $ENV_FILE; $*"
fi

exec docker exec -it "$NAME" bash --rcfile "$ENV_FILE"
